function translateValue(value) {
  if (currentLocale !== "en" || !value) return value;
  const exact = EN.get(value.trim());
  if (exact) return value.replace(value.trim(), exact);
  for (const [pattern, replacement] of PATTERNS) {
    if (pattern.test(value.trim())) return value.replace(value.trim(), value.trim().replace(pattern, replacement));
  }
  return value;
}

function localizeNode(node) {
  if (currentLocale !== "en") return;
  if (node.nodeType === Node.TEXT_NODE) {
    const translated = translateValue(node.nodeValue || "");
    if (translated !== node.nodeValue) node.nodeValue = translated;
    return;
  }
  if (!(node instanceof Element)) return;
  for (const attribute of ["aria-label", "title", "placeholder"]) {
    if (node.hasAttribute(attribute)) node.setAttribute(attribute, translateValue(node.getAttribute(attribute)));
  }
  node.childNodes.forEach(localizeNode);
}

export function setDashboardLocale(locale) {
  currentLocale = locale === "en" ? "en" : "zh-CN";
  document.documentElement.lang = currentLocale;
  document.title = currentLocale === "en" ? "AI Resource Radar" : "AI 免费资源雷达";
  localizeNode(document.documentElement);
  if (!observer) {
    observer = new MutationObserver((mutations) => {
      if (currentLocale !== "en") return;
      mutations.forEach((mutation) => {
        if (mutation.type === "characterData") localizeNode(mutation.target);
        mutation.addedNodes.forEach(localizeNode);
      });
    });
    observer.observe(document.documentElement, { childList: true, characterData: true, subtree: true });
  }
}

